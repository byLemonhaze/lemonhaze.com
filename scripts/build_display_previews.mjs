// Resize display previews only; originals and downloads remain unchanged.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { chromium } from 'playwright';
import { CAROUSEL_WORK_IDS, SELECTED_SERIES_COVERS, selectedWorks } from '../src/curation/selection.js';
import { fetchFeaturedCollections } from '../src/data/featured-collections.js';
import { assembleArtworkCatalog } from '../src/data/catalog.js';
import { normalizeBBCollection } from '../src/data.js';
import { getArtworkImageSrc } from '../src/renderers/gallery.js';

const root=new URL('../',import.meta.url);
const read=async path=>JSON.parse(await readFile(new URL(path,root),'utf8'));
const originalFetch=globalThis.fetch;
let featured;
try {
    globalThis.fetch=async url=>new Response(JSON.stringify(await read('public'+url)));
    featured=await fetchFeaturedCollections({strict:true});
} finally {globalThis.fetch=originalFetch;}
const catalog=assembleArtworkCatalog(await read('public/data/provenance.json'),normalizeBBCollection(await read('public/data/collections/best-before.json')),featured);
import { FEATURED_PAINT_ENGINES } from '../src/data/paint-engines.js';
const works=selectedWorks(catalog,[...new Set([...CAROUSEL_WORK_IDS,...Object.values(SELECTED_SERIES_COVERS),'0c57ce6325d8da6242488d453c13bac0e1e1eaca6a5b3bf4078a6bdd6768d49di0','87a923ac2114f0331cf75c65a5085baeda31993413d7d1b61a3f4ce7f73345cci0'])]);
const liminal=catalog.find(w=>w.series==='Liminality'&&w.role==='parent')||catalog.find(w=>w.collection==='Liminality');
if(liminal)works.push(liminal);
const sources=[...new Set([...works.map(getArtworkImageSrc),...FEATURED_PAINT_ENGINES.map(e=>`https://cdn.lemonhaze.com/assets/assets/${e.image||e.id+'.png'}`)])];
const cache=join(tmpdir(),'lemonhaze-social-originals');
const output=new URL('public/previews/',root);await mkdir(output,{recursive:true});await mkdir(cache,{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage();
const manifest={};
try {
 for(const src of sources){
  let bytes;
  if(src.startsWith('/'))bytes=await readFile(new URL('public'+src,root));
  else {
   const file=join(cache,createHash('sha256').update(src).digest('hex'));
   try{bytes=await readFile(file);}catch{
    let response=await fetch(src,{signal:AbortSignal.timeout(60000)});
    if ((!response.ok || !response.headers.get('content-type')?.startsWith('image/')) && src.startsWith('https://ordinals.com/content/')) {
      response=await fetch('https://cdn.lemonhaze.com/assets/assets/'+src.split('/').pop()+'.png',{signal:AbortSignal.timeout(60000)});
    }
    if(!response.ok||!response.headers.get('content-type')?.startsWith('image/'))throw Error('Invalid source '+src);
    bytes=Buffer.from(await response.arrayBuffer());await writeFile(file,bytes);
   }
  }
  const data='data:application/octet-stream;base64,'+bytes.toString('base64');
  const resized=await page.evaluate(async data=>{
   const image=new Image();image.src=data;await image.decode();
   const ratio=Math.min(1,1600/image.naturalWidth,1600/image.naturalHeight);
   const canvas=document.createElement('canvas');canvas.width=Math.round(image.naturalWidth*ratio);canvas.height=Math.round(image.naturalHeight*ratio);
   canvas.getContext('2d').drawImage(image,0,0,canvas.width,canvas.height);
   return canvas.toDataURL('image/webp',.76).split(',')[1];
  },data);
  const result=Buffer.from(resized,'base64');
  const filename=createHash('sha256').update(result).digest('hex').slice(0,16)+'.webp';
  await writeFile(new URL(filename,output),result);manifest[src]='/previews/'+filename;
  console.log(`${Math.round(bytes.length/1024)} KB -> ${Math.round(result.length/1024)} KB`);
 }
 await writeFile(new URL('src/curation/preview-images.js',root),'// Generated by scripts/build_display_previews.mjs. Display only.\nexport const PREVIEW_IMAGES = '+JSON.stringify(manifest,null,2)+';\nexport const displayPreview = src => PREVIEW_IMAGES[src] || src;\n');
}finally{await browser.close();}
